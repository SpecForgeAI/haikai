    /**
     * Test wrapper around the real {@link JdbcTemplate} that lets a single
     * test flip into "throw on update" mode after seeding, simulating a
     * mid-commit JDBC failure to drive the atomic rollback test (safety
     * property (a)). All other JdbcTemplate calls delegate to the real bean
     * so seed + tear-down + the rest of the test class run untouched.
     *
     * <p>Selective copy's commit path uses {@code update(String, Object...)}
     * for both INSERTs (via {@code insertRow}) and UPDATEs (via
     * {@code updateRow}). Overriding that single method gives precise
     * coverage of every commit-write call site without disturbing reads
     * (queryForList) or batch operations.</p>
     */
    public static class ThrowingJdbcTemplate extends JdbcTemplate {
        public final AtomicReference<RuntimeException> throwOn = new AtomicReference<>();
        public final java.util.concurrent.atomic.AtomicInteger updateInvocations =
            new java.util.concurrent.atomic.AtomicInteger(0);

        public ThrowingJdbcTemplate(DataSource dataSource) {
            super(dataSource);
        }

        @Override
        public int update(String sql, Object... args) throws DataAccessException {
            updateInvocations.incrementAndGet();
            RuntimeException pending = throwOn.get();
            if (pending != null) {
                throw pending;
            }
            return super.update(sql, args);
        }
    }

    @TestConfiguration
    static class SelectiveCopyTestConfig {
        @Bean
        @Primary
        public JdbcTemplate testJdbcTemplate(DataSource dataSource) {
            return new ThrowingJdbcTemplate(dataSource);
        }
    }

