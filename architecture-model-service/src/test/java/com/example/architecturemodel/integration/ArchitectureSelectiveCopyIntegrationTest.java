    private void seedArchitecture(UUID id, UUID projectId, String name,
                                  String description, boolean archived) {
        ArchitectureEntity arch = ArchitectureEntity.builder()
            .id(id)
            .projectId(projectId)
            .name(name)
            .description(description)
            .archived(archived)
            .build();
        architectureRepository.save(arch);
    }

    private String newModelFile(UUID architectureId) {
        String mfId = "mf-" + UUID.randomUUID();
        modelFileRepository.save(ModelFileEntity.builder()
            .id(mfId)
            .filename("mf-" + UUID.randomUUID())
            .description("Test model file")
            .createdAt(OffsetDateTime.now())
            .updatedAt(OffsetDateTime.now())
            .isDefault(false)
            .projectId(projectId)
            .architectureId(architectureId)
            .build());
        return mfId;
    }

    private void insertApplication(String id, String mfId, String name,
                                   String abbrev, UUID archId) {
        jdbcTemplate.update(
            "INSERT INTO applications (id, model_file_id, name, abbreviation, architecture_id) "
                + "VALUES (?, ?, ?, ?, ?)",
            id, mfId, name, abbrev, archId);
    }

    private void insertService(String id, String mfId, String appId,
                               String name, UUID archId) {
        jdbcTemplate.update(
            "INSERT INTO services (id, model_file_id, application_id, name, architecture_id) "
                + "VALUES (?, ?, ?, ?, ?)",
            id, mfId, appId, name, archId);
    }
