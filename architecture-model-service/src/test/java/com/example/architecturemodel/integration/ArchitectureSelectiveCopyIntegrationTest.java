    /**
     * Test 8 (safety property (a)): atomic rollback on mid-commit failure.
     *
     * <p>Wires a {@link ThrowingJdbcTemplate} (via {@link SelectiveCopyTestConfig})
     * that throws on the first {@code update(String, Object[])} call once
     * armed. Selective copy's commit path performs all writes via that
     * single method (both INSERTs and UPDATEs), so arming it after seeding
     * guarantees we trip the very first commit-write call.</p>
     *
     * <p>Seeds source with 1 application + 1 service that references it,
     * plus a target row with the same UUID as the application (a conflict
     * the test resolves to {@code overwrite} so the commit attempts BOTH
     * an UPDATE and an INSERT). Arms the throwing wrapper, runs commit,
     * and asserts:</p>
     *
     * <ul>
     *   <li>commit surfaces the exception;</li>
     *   <li>the target row's name is UNCHANGED (the {@code overwrite} UPDATE
     *       was rolled back);</li>
     *   <li>no new service row was inserted in the target;</li>
     *   <li>the source rows are byte-for-byte untouched.</li>
     * </ul>
     */
    @Test
    @DisplayName("Test 8 (a): commit rolls back atomically when a mid-commit JDBC update fails")
    void testCommitAtomicRollbackOnMidCommitFailure() {
        UUID sourceArchId = UUID.randomUUID();
        UUID targetArchId = UUID.randomUUID();
        seedArchitecture(sourceArchId, projectId, "Source Atomic", null, false);
        seedArchitecture(targetArchId, projectId, "Target Atomic", null, false);

        String srcMfId = newModelFile(sourceArchId);
        String tgtMfId = newModelFile(targetArchId);

        // Source has app + service referencing it.
        UUID sharedAppId = UUID.randomUUID();
        UUID sourceSvcId = UUID.randomUUID();
        insertApplication(sharedAppId.toString(), srcMfId, "Source App", "SRC", sourceArchId);
        insertService(sourceSvcId.toString(), srcMfId, sharedAppId.toString(),
            "Source Service", sourceArchId);
        // Target has the SAME app uuid but different name — this is the conflict
        // the test will resolve to overwrite (forcing an UPDATE write call).
        insertApplication(sharedAppId.toString(), tgtMfId, "Target App (must remain)", "TGT",
            targetArchId);

        // Snapshot pre-commit state so we can assert nothing changed.
        long applicationsBefore = jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM applications", Long.class);
        long servicesBefore = jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM services", Long.class);
        Map<String, Object> targetAppBefore = jdbcTemplate.queryForMap(
            "SELECT name, abbreviation FROM applications WHERE id = ? AND architecture_id = ?",
            sharedAppId.toString(), targetArchId);
        Map<String, Object> sourceAppBefore = jdbcTemplate.queryForMap(
            "SELECT name FROM applications WHERE id = ? AND architecture_id = ?",
            sharedAppId.toString(), sourceArchId);
        Map<String, Object> sourceSvcBefore = jdbcTemplate.queryForMap(
            "SELECT name, application_id FROM services WHERE id = ? AND architecture_id = ?",
            sourceSvcId.toString(), sourceArchId);

        // Arm the throwing wrapper to fail on the first commit-time write.
        assertThat(jdbcTemplate)
            .as("the test must be wired with the ThrowingJdbcTemplate via SelectiveCopyTestConfig")
            .isInstanceOf(ThrowingJdbcTemplate.class);
        ThrowingJdbcTemplate throwing = (ThrowingJdbcTemplate) jdbcTemplate;
        throwing.throwOn.set(new RuntimeException("Simulated mid-commit JDBC failure"));

        try {
            assertThatThrownBy(() -> selectiveCopyService.commit(
                projectId,
                targetArchId,
                new SelectiveCopyCommitRequest(
                    sourceArchId,
                    List.of(sharedAppId, sourceSvcId),
                    List.of(new ResolutionItem(sharedAppId, "overwrite")))))
                .as("commit must surface the simulated JDBC failure")
                .isInstanceOf(RuntimeException.class)
                .hasMessageContaining("Simulated mid-commit JDBC failure");
        } finally {
            // Disarm before assertions / teardown so the verification queries
            // and cleanup deletes can run unimpeded.
            throwing.throwOn.set(null);
        }

        // (a) Target row's name MUST be unchanged — the overwrite UPDATE
        // was rolled back.
        Map<String, Object> targetAppAfter = jdbcTemplate.queryForMap(
            "SELECT name, abbreviation FROM applications WHERE id = ? AND architecture_id = ?",
            sharedAppId.toString(), targetArchId);
        assertThat(targetAppAfter.get("name"))
            .as("safety property (a): the overwrite UPDATE must be rolled back")
            .isEqualTo(targetAppBefore.get("name"));
        assertThat(targetAppAfter.get("abbreviation"))
            .isEqualTo(targetAppBefore.get("abbreviation"));

        // (a) No new service row was inserted in target.
        long applicationsAfter = jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM applications", Long.class);
        long servicesAfter = jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM services", Long.class);
        assertThat(applicationsAfter)
            .as("safety property (a): no new application row should remain after rollback")
            .isEqualTo(applicationsBefore);
        assertThat(servicesAfter)
            .as("safety property (a): no new service row should remain after rollback")
            .isEqualTo(servicesBefore);

        // (a) Source rows are untouched (selective copy never writes to source).
        Map<String, Object> sourceAppAfter = jdbcTemplate.queryForMap(
            "SELECT name FROM applications WHERE id = ? AND architecture_id = ?",
            sharedAppId.toString(), sourceArchId);
        assertThat(sourceAppAfter.get("name")).isEqualTo(sourceAppBefore.get("name"));
        Map<String, Object> sourceSvcAfter = jdbcTemplate.queryForMap(
            "SELECT name, application_id FROM services WHERE id = ? AND architecture_id = ?",
            sourceSvcId.toString(), sourceArchId);
        assertThat(sourceSvcAfter.get("name")).isEqualTo(sourceSvcBefore.get("name"));
        assertThat(sourceSvcAfter.get("application_id"))
            .isEqualTo(sourceSvcBefore.get("application_id"));
    }

    /**
     * Test 9 (safety property (g)): {@code discovery_run} rows are NOT
     * copied by selective copy.
     *
     * <p>The Discovery domain is permanent, time-stamped provenance for the
     * source architecture and must never appear under the target after
     * selective copy (Discovery is locked one-run-per-architecture per the
     * spec). Threads are file-based and project-scoped, so they too are
     * out of scope for the JDBC commit path — by inspection the service
     * NEVER touches thread storage (it has no ThreadStore dependency
     * injected at all), making the Discovery-table assertion the
     * load-bearing demonstration that excluded scopes are honoured.</p>
     *
     * <p>Seeds source with: 1 application + 1 discovery_run pointing at the
     * source architecture. Runs a normal commit selecting the application
     * (no conflict — target is empty). Asserts:</p>
     *
     * <ul>
     *   <li>commit succeeded and copied the application;</li>
     *   <li>target architecture has zero {@code discovery_run} rows;</li>
     *   <li>source's {@code discovery_run} is byte-for-byte untouched
     *       (id, project, status all unchanged);</li>
     *   <li>the total {@code discovery_run} count is unchanged
     *       (no new rows of any kind).</li>
     * </ul>
     */
    @Test
    @DisplayName("Test 9 (g): selective copy does not touch discovery_run rows in either direction")
    void testCommitDoesNotCopyDiscoveryRuns() {
        UUID sourceArchId = UUID.randomUUID();
        UUID targetArchId = UUID.randomUUID();
        seedArchitecture(sourceArchId, projectId, "Source With Discovery", null, false);
        seedArchitecture(targetArchId, projectId, "Target", null, false);

        String srcMfId = newModelFile(sourceArchId);
        // No model file in target — the application is a no-conflict copy.

        UUID appId = UUID.randomUUID();
        insertApplication(appId.toString(), srcMfId, "Source App", "SRC", sourceArchId);

        // Seed a discovery_run pointing at the source architecture. We use
        // raw JDBC insert rather than the JPA repository because the entity
        // requires a JSONB column with a sensible default and going through
        // raw SQL keeps the test focused on the exclusion property (the
        // service must never read or write this table).
        UUID discoveryRunId = UUID.randomUUID();
        DiscoveryRunEntity run = DiscoveryRunEntity.builder()
            .id(discoveryRunId)
            .projectId(projectId)
            .architectureId(sourceArchId)
            .status("COMPLETED")
            .build();
        discoveryRunRepository.save(run);

        long discoveryRunsBefore = discoveryRunRepository.count();
        long sourceDiscoveryRunsBefore = jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM discovery_run WHERE architecture_id = ?",
            Long.class, sourceArchId);
        assertThat(sourceDiscoveryRunsBefore)
            .as("source must have its discovery_run seeded")
            .isEqualTo(1L);

        // Commit the application (a no-conflict, no-auto-include copy).
        SelectiveCopyCommitResponse result = selectiveCopyService.commit(
            projectId,
            targetArchId,
            new SelectiveCopyCommitRequest(
                sourceArchId,
                List.of(appId),
                List.of()));

        assertThat(result.copied())
            .as("the application must have been copied verbatim into target")
            .isEqualTo(1);

        // (g) Target architecture has zero discovery_run rows.
        Long targetDiscoveryRunCount = jdbcTemplate.queryForObject(
            "SELECT COUNT(*) FROM discovery_run WHERE architecture_id = ?",
            Long.class, targetArchId);
        assertThat(targetDiscoveryRunCount)
            .as("safety property (g): target architecture must have zero discovery_run rows")
            .isEqualTo(0L);

        // (g) Total discovery_run count is unchanged — no new rows of any
        // kind were created by the commit path.
        long discoveryRunsAfter = discoveryRunRepository.count();
        assertThat(discoveryRunsAfter)
            .as("safety property (g): discovery_run total count must be unchanged")
            .isEqualTo(discoveryRunsBefore);

        // (g) Source's discovery_run is byte-for-byte untouched.
        DiscoveryRunEntity sourceRunStill = discoveryRunRepository.findById(discoveryRunId)
            .orElseThrow(() -> new AssertionError("source's discovery_run was deleted"));
        assertThat(sourceRunStill.getArchitectureId()).isEqualTo(sourceArchId);
        assertThat(sourceRunStill.getProjectId()).isEqualTo(projectId);
        assertThat(sourceRunStill.getStatus()).isEqualTo("COMPLETED");

        // The application copy itself worked end-to-end (sanity check).
        Map<String, Object> targetApp = jdbcTemplate.queryForMap(
            "SELECT name, abbreviation FROM applications WHERE id = ? AND architecture_id = ?",
            appId.toString(), targetArchId);
        assertThat(targetApp.get("name")).isEqualTo("Source App");
        assertThat(targetApp.get("abbreviation")).isEqualTo("SRC");
    }

