    /**
     * Test 1 (safety property (b)): preflight detects a {@code same_uuid}
     * conflict when an element id in the user's selection already exists in
     * the target architecture by UUID match.
     *
     * Seeds source with 2 applications (no FK references). Seeds target with
     * the SAME UUID for one of them. Runs preflight selecting both apps.
     * Asserts: 1 conflict reported with conflictReason='same_uuid' for the
     * shared app's id; the other app produces no conflict.
     */
    @Test
    @DisplayName("Test 1 (b): preflight reports same_uuid conflict when target already has the id")
    void testPreflightDetectsSameUuidConflict() {
        UUID sourceArchId = UUID.randomUUID();
        UUID targetArchId = UUID.randomUUID();
        seedArchitecture(sourceArchId, projectId, "Source", null, false);
        seedArchitecture(targetArchId, projectId, "Target", null, false);

        // Two model files (one per architecture).
        String srcMfId = newModelFile(sourceArchId);
        String tgtMfId = newModelFile(targetArchId);

        // Two applications in source. The first SHARES its UUID with a row in
        // the target; the second is unique to source.
        UUID sharedAppId = UUID.randomUUID();
        UUID uniqueAppId = UUID.randomUUID();
        insertApplication(sharedAppId.toString(), srcMfId, "Shared App", "SHA", sourceArchId);
        insertApplication(uniqueAppId.toString(), srcMfId, "Unique App", "UNI", sourceArchId);

        // Pre-seed the target with the same UUID for the shared app.
        insertApplication(sharedAppId.toString(), tgtMfId, "Shared App (target name)", "SHA", targetArchId);

        // Run preflight selecting both.
        SelectiveCopyPreflightResponse response = selectiveCopyService.preflight(
            projectId,
            targetArchId,
            new SelectiveCopyPreflightRequest(
                sourceArchId,
                List.of(sharedAppId, uniqueAppId)));

        // Exactly one conflict — the shared app — with reason same_uuid.
        assertThat(response.conflicts())
            .as("preflight should report a same_uuid conflict for the shared app id")
            .hasSize(1);
        ConflictItem conflict = response.conflicts().get(0);
        assertThat(conflict.elementId()).isEqualTo(sharedAppId);
        assertThat(conflict.conflictReason()).isEqualTo("same_uuid");
        assertThat(conflict.elementType()).isEqualTo("applications");
        // Auto-included is empty because there are no FK references.
        assertThat(response.autoIncluded()).isEmpty();
        // Summary counts match.
        assertThat(response.summary().totalSelected()).isEqualTo(2);
        assertThat(response.summary().conflictCount()).isEqualTo(1);
        assertThat(response.summary().autoIncludedCount()).isEqualTo(0);
    }

    /**
     * Test 2 (safety property (d) - missing branch): preflight smart cascading
     * auto-includes a referenced element absent from the target.
     *
     * Seeds source with 1 application + 1 service referencing that
     * application via {@code application_id}. Target is empty. Runs preflight
     * selecting only the service. Asserts: the application appears in
     * {@code autoIncluded} with the service's name as {@code includedBecause}.
     */
    @Test
    @DisplayName("Test 2 (d-missing): preflight auto-includes a missing FK reference")
    void testPreflightAutoIncludesMissingReference() {
        UUID sourceArchId = UUID.randomUUID();
        UUID targetArchId = UUID.randomUUID();
        seedArchitecture(sourceArchId, projectId, "Source", null, false);
        seedArchitecture(targetArchId, projectId, "Target", null, false);

        String srcMfId = newModelFile(sourceArchId);

        UUID appId = UUID.randomUUID();
        insertApplication(appId.toString(), srcMfId, "Parent App", "PA", sourceArchId);

        UUID svcId = UUID.randomUUID();
        insertService(svcId.toString(), srcMfId, appId.toString(), "Selected Service", sourceArchId);

        // Run preflight selecting ONLY the service.
        SelectiveCopyPreflightResponse response = selectiveCopyService.preflight(
            projectId,
            targetArchId,
            new SelectiveCopyPreflightRequest(sourceArchId, List.of(svcId)));

        // No conflicts (target is empty).
        assertThat(response.conflicts()).isEmpty();
        // The referenced application must be in autoIncluded with the
        // service's name as includedBecause.
        assertThat(response.autoIncluded())
            .as("preflight must auto-include the application referenced by the service")
            .hasSize(1);
        AutoIncludedItem auto = response.autoIncluded().get(0);
        assertThat(auto.elementId()).isEqualTo(appId);
        assertThat(auto.elementType()).isEqualTo("applications");
        assertThat(auto.includedBecause()).isEqualTo("Selected Service");
        assertThat(response.summary().autoIncludedCount()).isEqualTo(1);
        assertThat(response.summary().conflictCount()).isEqualTo(0);
    }

    /**
     * Test 3 (safety property (d) - reuse branch): preflight silently reuses
     * a referenced element when it ALREADY exists in the target by UUID match.
     * NO entry in {@code conflicts} (the user didn't select it) and NO entry
     * in {@code autoIncluded} (it's already there — no need to copy).
     *
     * Seeds source with 1 application + 1 service. Seeds target with the
     * SAME application UUID. Runs preflight selecting only the service.
     * Asserts: zero auto-included entries.
     */
    @Test
    @DisplayName("Test 3 (d-reuse): preflight reuses a referenced element already in target — no auto-include")
    void testPreflightReusesReferenceAlreadyInTarget() {
        UUID sourceArchId = UUID.randomUUID();
        UUID targetArchId = UUID.randomUUID();
        seedArchitecture(sourceArchId, projectId, "Source", null, false);
        seedArchitecture(targetArchId, projectId, "Target", null, false);

        String srcMfId = newModelFile(sourceArchId);
        String tgtMfId = newModelFile(targetArchId);

        // The application appears in BOTH architectures with the SAME UUID.
        UUID sharedAppId = UUID.randomUUID();
        insertApplication(sharedAppId.toString(), srcMfId, "Source App", "SA", sourceArchId);
        insertApplication(sharedAppId.toString(), tgtMfId, "Target App", "SA", targetArchId);

        // Service exists only in source, references the shared application.
        UUID svcId = UUID.randomUUID();
        insertService(svcId.toString(), srcMfId, sharedAppId.toString(), "Selected Service", sourceArchId);

        // Run preflight selecting ONLY the service.
        SelectiveCopyPreflightResponse response = selectiveCopyService.preflight(
            projectId,
            targetArchId,
            new SelectiveCopyPreflightRequest(sourceArchId, List.of(svcId)));

        // No conflicts (the service is unique to source) and crucially NO
        // autoIncluded — the application is silently reused from the target.
        assertThat(response.conflicts())
            .as("the service is unique to source so no conflicts")
            .isEmpty();
        assertThat(response.autoIncluded())
            .as("the application is already in target by UUID match — must be silently reused")
            .isEmpty();
        assertThat(response.summary().autoIncludedCount()).isEqualTo(0);
    }

