/**
 * End-to-end integration test for {@link ArchitectureSelectiveCopyService},
 * asserting the nine critical safety properties at the database level.
 *
 * <h2>Test scope (Task Groups 4 + 11 of spec #7)</h2>
 *
 * <p>This is the authoritative test for selective-copy graph correctness;
 * service-level tests in {@code ArchitectureSelectiveCopyServiceTest} cover
 * validation paths with mocked JDBC. Each test seeds two architectures
 * (source + target) in the same project, runs preflight and/or commit, and
 * inspects the resulting database state.</p>
 *
 * <ol>
 *   <li><b>Preflight: same_uuid conflict detected</b> — safety property (b).</li>
 *   <li><b>Preflight: smart cascading auto-include for missing reference</b>
 *       — safety property (d) - missing branch.</li>
 *   <li><b>Preflight: smart cascading reuse when reference exists in target</b>
 *       — safety property (d) - reuse branch.</li>
 *   <li><b>Commit: skip action</b> — safety property (c) - skip.</li>
 *   <li><b>Commit: overwrite action</b> — safety property (c) - overwrite.</li>
 *   <li><b>Commit: duplicate action with FK rewiring</b> — safety property (c)
 *       - duplicate (and intra-copy-set FK rewiring).</li>
 *   <li><b>Refuse archived source</b> — safety property (e). Also asserts
 *       same-architecture refusal — safety property (f).</li>
 *   <li><b>Atomic rollback on mid-commit failure</b> — safety property (a).
 *       Added in Task Group 11 gap fill: wires a {@link ThrowingJdbcTemplate}
 *       that throws on the first {@code update(String, Object[])} write call
 *       once armed; asserts the commit's {@code @Transactional} boundary
 *       rolls back ALL writes (no new rows in target, no UPDATE persisted
 *       from earlier overwrite actions either).</li>
 *   <li><b>Discovery + threads not copied</b> — safety property (g). Added in
 *       Task Group 11 gap fill: seeds the source with a {@code discovery_run}
 *       row, runs a normal selective copy, asserts the target architecture
 *       has zero {@code discovery_run} rows after commit and the source's
 *       run is byte-for-byte untouched (Discovery is locked one-run/architecture
 *       per spec).</li>
 * </ol>
 *
 * <h2>Schema setup caveats</h2>
 *
 * <p>The H2 test schema is generated by JPA's {@code create-drop} from the
 * entity model. Two adjustments are required for these tests to run:</p>
 *
 * <ol>
 *   <li><b>{@code architecture_id} column.</b> Only entities that declare an
 *       {@code architectureId} field (currently {@code model_files},
 *       {@code architecture_tag}, {@code discovery_run}, {@code temporary_diagrams})
 *       get an {@code architecture_id} column on their table. This integration
 *       test therefore manually adds {@code architecture_id} columns to the
 *       additional tables it exercises ({@code applications}, {@code services})
 *       in {@link #setUp()}. In production the same columns are added by
 *       Liquibase changeset 089. This mirrors the pattern in
 *       {@code ArchitectureCloneIntegrationTest}.</li>
 *   <li><b>Composite primary key {@code (id, architecture_id)}.</b> The
 *       JPA-generated H2 schema treats the {@code id} column as a global
 *       PRIMARY KEY, mirroring the production Liquibase schema. The
 *       same-UUID-conflict scenario this test asserts requires that two
 *       different architectures legitimately hold a row with the same
 *       {@code id} value (e.g. a row cloned and then re-imported via selective
 *       copy). To make that scenario representable in the test fixture, the
 *       global single-column PK is dropped and replaced with a composite
 *       {@code (id, architecture_id)} primary key for the two tables this
 *       test exercises. Production behaviour is unchanged — this is purely a
 *       test-fixture relaxation that lets the integration test express the
 *       conflict scenario the service is built to resolve. The production
 *       schema retains the global PK; selective copy's
 *       {@link ArchitectureSelectiveCopyService} relies on the (id,
 *       architecture_id) lookups inside its own logic so behaviour is
 *       unaffected by the relaxation.
 *
 *       <p><b>Documentation note (Group 11):</b> because the production schema
 *       enforces a global single-column PK on {@code id}, the {@code same_uuid}
 *       conflict path is essentially unreachable in normal production flow —
 *       two rows with the same {@code id} would be rejected by the PK
 *       constraint long before selective copy got to run. The {@code same_uuid}
 *       detection is defensive code that future-proofs the service against
 *       schema changes (e.g. if the global PK is ever relaxed for multi-arch
 *       support) and against UUID collisions inserted via raw SQL or via a
 *       data import path that bypasses the JPA layer. This is a deliberate
 *       defence-in-depth choice; the gap is flagged here for transparency
 *       rather than fixed by this spec — schema changes are tracked
 *       separately.</p></li>
 * </ol>
 *
 * <h2>Element IDs are plain UUIDs (no prefix)</h2>
 *
 * <p>Unlike the clone-service test, the selective-copy service exposes a
 * {@code List<UUID> elementIds} parameter that is converted to strings via
 * {@code id.toString()} and matched against the {@code id} column in the
 * source tables. The existing application + service rows therefore must use
 * plain UUID strings for their primary keys (no {@code "app-"} or
 * {@code "svc-"} prefix that the clone test uses). Foreign-key columns like
 * {@code services.application_id} likewise hold plain UUID strings so the
 * cascading walk's {@code looksLikeUuid()} predicate matches.</p>
 *
 * <h2>Transaction boundaries</h2>
 *
 * <p>Tests are NOT annotated {@code @Transactional} so the commit's own
 * {@code @Transactional} boundary is real. Each test cleans up its own seed
 * data in {@link #tearDown()} via direct JDBC deletes.</p>
 *
 * Spec: Multi-Architecture Selective Cross-Architecture Copy (Spec #7)
 * Task Group 4: Backend integration test for selective-copy correctness.
 * Task Group 11: gap-fill tests for safety properties (a) atomic rollback
 *                and (g) excluded-scope (Discovery + threads) verification.
 */
