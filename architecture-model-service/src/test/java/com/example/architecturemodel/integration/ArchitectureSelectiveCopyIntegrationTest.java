    @BeforeEach
    void setUp() {
        projectId = UUID.randomUUID();

        // Reset the throwing wrapper each test (avoid cross-test bleed since
        // the Spring context is reused across tests within a class).
        if (jdbcTemplate instanceof ThrowingJdbcTemplate t) {
            t.throwOn.set(null);
            t.updateInvocations.set(0);
        }

        // (1) Add architecture_id columns to JPA-managed tables that need them
        // for the selective-copy walk. JPA's create-drop only adds the column
        // for entities that declare the field. IF NOT EXISTS makes this
        // idempotent across test methods (Spring context is cached).
        ensureArchitectureIdColumn("applications");
        ensureArchitectureIdColumn("services");

        // (2) Replace the global single-column PK on (id) with a composite
        // (id, architecture_id) PK so the same-UUID-conflict scenario is
        // representable. See class-level Javadoc for rationale.
        relaxToCompositePrimaryKey("applications");
        relaxToCompositePrimaryKey("services");
    }

    @AfterEach
    void tearDown() {
        // Clear throwOn first so the cleanup deletes don't trip the wrapper.
        if (jdbcTemplate instanceof ThrowingJdbcTemplate t) {
            t.throwOn.set(null);
        }

        // Clean up everything (and anything copied from it). We can't use
        // @Transactional on the test itself because that would mask the
        // commit's own transaction boundary.
        jdbcTemplate.update("DELETE FROM services WHERE 1=1");
        jdbcTemplate.update("DELETE FROM applications WHERE 1=1");
        jdbcTemplate.update("DELETE FROM model_files WHERE 1=1");
        try {
            jdbcTemplate.update("DELETE FROM discovery_run WHERE 1=1");
        } catch (DataAccessException ignored) {
            // Table may not exist in some test profiles.
        }
        jdbcTemplate.update("DELETE FROM architecture_tag WHERE 1=1");
        jdbcTemplate.update("DELETE FROM architecture WHERE 1=1");
    }

    private void ensureArchitectureIdColumn(String table) {
        try {
            jdbcTemplate.execute(
                "ALTER TABLE " + table + " ADD COLUMN IF NOT EXISTS architecture_id UUID");
        } catch (DataAccessException e) {
            throw new IllegalStateException(
                "Failed to ensure architecture_id column on " + table + ": " + e.getMessage(), e);
        }
    }

    /**
     * Replaces the table's single-column PK on {@code id} with a composite
     * {@code (id, architecture_id)} PK so two architectures can hold rows
     * with the same {@code id} value. Idempotent: silently skips if the
     * composite PK is already in place from a previous test method (the
     * Spring context — and therefore the H2 schema — is cached across
     * methods within this class).
     */
    private void relaxToCompositePrimaryKey(String table) {
        // First, ensure architecture_id is NOT NULL (a PK column cannot be
        // nullable). H2 silently no-ops if it's already NOT NULL.
        try {
            // Backfill any pre-existing rows (defensive — should be none in a
            // freshly-cleaned schema) before flipping NOT NULL.
            jdbcTemplate.execute(
                "UPDATE " + table + " SET architecture_id = '00000000-0000-0000-0000-000000000000' "
                    + "WHERE architecture_id IS NULL");
            jdbcTemplate.execute(
                "ALTER TABLE " + table + " ALTER COLUMN architecture_id SET NOT NULL");
        } catch (DataAccessException ignored) {
            // Already NOT NULL or the table is empty — both fine.
        }

        // Drop the existing single-column PK, then add the composite PK. H2's
        // generated PK constraint is named after the table; querying
        // INFORMATION_SCHEMA finds it portably.
        try {
            String pkName = jdbcTemplate.queryForObject(
                "SELECT CONSTRAINT_NAME FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS "
                    + "WHERE TABLE_NAME = ? AND CONSTRAINT_TYPE = 'PRIMARY KEY'",
                String.class, table.toUpperCase());
            if (pkName != null) {
                jdbcTemplate.execute("ALTER TABLE " + table + " DROP CONSTRAINT " + pkName);
            }
        } catch (DataAccessException ignored) {
            // No PK present (already relaxed) — fall through.
        }
        try {
            jdbcTemplate.execute(
                "ALTER TABLE " + table + " ADD PRIMARY KEY (id, architecture_id)");
        } catch (DataAccessException ignored) {
            // Composite PK already exists — ignore (idempotent across test
            // methods within the cached Spring context).
        }
    }

