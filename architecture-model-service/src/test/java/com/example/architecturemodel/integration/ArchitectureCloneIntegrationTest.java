    /**
     * Test wrapper around the real {@link JdbcTemplate} that lets a single
     * test flip into "throw on batchUpdate" mode after the first N
     * invocations, simulating a mid-clone JDBC failure to drive the atomic
     * rollback test (safety property (a)). All other JdbcTemplate calls
     * delegate to the real bean so the rest of the suite runs untouched.
     */
    public static class ThrowingJdbcTemplate extends JdbcTemplate {
        public final AtomicReference<RuntimeException> throwOn = new AtomicReference<>();
        public final java.util.concurrent.atomic.AtomicInteger batchInvocations =
            new java.util.concurrent.atomic.AtomicInteger(0);

        public ThrowingJdbcTemplate(DataSource dataSource) {
            super(dataSource);
        }

        @Override
        public int[] batchUpdate(String sql, List<Object[]> batchArgs) throws DataAccessException {
            batchInvocations.incrementAndGet();
            RuntimeException pending = throwOn.get();
            if (pending != null) {
                throw pending;
            }
            return super.batchUpdate(sql, batchArgs);
        }
    }

    @TestConfiguration
    static class CloneTestConfig {
        @Bean
        @Primary
        public JdbcTemplate testJdbcTemplate(DataSource dataSource) {
            return new ThrowingJdbcTemplate(dataSource);
        }
    }

    @Autowired
    private ArchitectureCloneService cloneService;

    @Autowired
    private ArchitectureRepository architectureRepository;

