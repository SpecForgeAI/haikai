    /**
     * Regression for the silent-skip gap: tables that lack an {@code architecture_id}
     * column (libraries + the whole infrastructure domain, all created after
     * changeset 089) are anchored to the architecture via
     * {@code model_file_id -> model_files.architecture_id}. The clone MUST copy
     * them via that chain rather than skip them. {@code environments} is a real
     * such table (its entity has {@code model_file_id} but no {@code architectureId},
     * and this test does NOT add the column), so it faithfully reproduces the
     * production schema. Before the fix the clone dropped these tables entirely,
     * so Suggest-from-current produced a target missing all infrastructure.
     */
    @Test
    @DisplayName("Clone copies model_file_id-scoped tables that lack architecture_id (infra/libraries), rewiring model_file_id")
    void testClonesModelFileScopedTableWithoutArchitectureIdColumn() {
        UUID sourceArchId = UUID.randomUUID();
        seedArchitecture(sourceArchId, projectId, "Current State", "Captured via Discovery");

        String mfId = "mf-" + UUID.randomUUID();
        ModelFileEntity modelFile = ModelFileEntity.builder()
            .id(mfId)
            .filename("model-file-" + UUID.randomUUID())
            .description("Source model file")
            .createdAt(OffsetDateTime.now())
            .updatedAt(OffsetDateTime.now())
            .isDefault(false)
            .projectId(projectId)
            .architectureId(sourceArchId)
            .build();
        modelFileRepository.save(modelFile);

        String envId = "env-" + UUID.randomUUID();
        jdbcTemplate.update(
            "INSERT INTO environments (id, model_file_id, name) VALUES (?, ?, ?)",
            envId, mfId, "Production Tier");

        ArchitectureDto cloned = cloneService.cloneArchitecture(
            projectId, sourceArchId, "Target State", "Designed from current", List.of());
        UUID newArchId = cloned.id();

        // The new model_file the cloned environment must be rewired to.
        List<Map<String, Object>> newMfs = jdbcTemplate.queryForList(
            "SELECT id FROM model_files WHERE architecture_id = ?", newArchId);
        assertThat(newMfs).hasSize(1);
        String newMfId = (String) newMfs.get(0).get("id");

        // The environment must be CLONED (not skipped), scoped via model_file_id.
        List<Map<String, Object>> clonedEnvs = jdbcTemplate.queryForList(
            "SELECT id, name, model_file_id FROM environments "
                + "WHERE model_file_id IN (SELECT id FROM model_files WHERE architecture_id = ?)",
            newArchId);
        assertThat(clonedEnvs)
            .as("environments is model_file_id-scoped (no architecture_id) and MUST be cloned, not skipped")
            .hasSize(1);
        Map<String, Object> env = clonedEnvs.get(0);
        assertThat(env.get("id")).isNotEqualTo(envId);            // fresh id
        assertThat(env.get("name")).isEqualTo("Production Tier"); // value preserved
        assertThat(env.get("model_file_id")).isEqualTo(newMfId);  // rewired to the new model_file

        // Source environment is untouched.
        List<Map<String, Object>> sourceEnvs = jdbcTemplate.queryForList(
            "SELECT id FROM environments WHERE model_file_id = ?", mfId);
        assertThat(sourceEnvs).hasSize(1);
        assertThat(sourceEnvs.get(0).get("id")).isEqualTo(envId);
    }

